# LeetCode 709 - To Lower Case (Easy)
#
# Given a string s, return the same string with every uppercase letter converted
# to lowercase. Everything that is not an uppercase letter is left alone.
#
# Example: 'Hello'   ->  'hello'
#          'LOVELY'  ->  'lovely'

# Upper case --> Lower case

class Solution(object):
    def toLowerCase(self, s):
        return lower(s)
        